async function run() {
  const replace = process.argv.includes("--replace")
  const uri = process.env.MONGODB_URI
  if (!uri) {
    console.error("MONGODB_URI not set")
    process.exit(1)
  }

  console.log("Connecting to", uri)
  await mongoose.connect(uri)

  if (replace) {
    console.log("⚠ --replace flag: deleting all existing TLDs...")
    const deleted = await DomainTld.deleteMany({})
    console.log(`  Deleted: ${deleted.deletedCount}`)
  }

  console.log(`Seeding ${SEED_DATA.length} TLDs...`)

  // Bulk upsert — idempotent
  const ops = SEED_DATA.map((row) => ({
    updateOne: {
      filter: { tld: row.tld },
      update: {
        $setOnInsert: { tld: row.tld },
        $set: {
          priceCost: row.price,
          renewCost: row.renew,
          priceSold: row.priceSold,
          renewSold: row.renewSold,
          isActive: row.isActive,
        },
      },
      upsert: true,
    },
  }))

  const result = await DomainTld.bulkWrite(ops, { ordered: false })
  console.log(`✔ Upserted: ${result.upsertedCount}, Modified: ${result.modifiedCount}`)

  const total = await DomainTld.countDocuments()
  console.log(`Total TLDs in DB: ${total}`)

  await mongoose.disconnect()
  console.log("Done.")
}

run().catch((err) => {
  console.error("Seed failed:", err)
  process.exit(1)
})
