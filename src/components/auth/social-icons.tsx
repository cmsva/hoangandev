function openPopup(provider: Provider) {
  const w = 500
  const h = 600
  const left = window.screenX + (window.outerWidth - w) / 2
  const top = window.screenY + (window.outerHeight - h) / 2
  window.open(
    `/api/auth/oauth/${provider}`,
    `oauth_${provider}`,
    `popup,width=${w},height=${h},left=${left},top=${top}`
  )
}

const OAUTH_ERROR_MESSAGES: Record<string, string> = {
  banned: "Tài khoản đã bị khóa",
  not_configured: "Phương thức này chưa được cấu hình",
  oauth_denied: "Bạn đã hủy đăng nhập",
  csrf_mismatch: "Phiên đăng nhập không hợp lệ, vui lòng thử lại",
  telegram_hash_invalid: "Xác thực Telegram thất bại",
}

export function SocialLoginRow({ label = "Hoặc tiếp tục với" }: { label?: string }) {
  React.useEffect(() => {
    const handler = (e: MessageEvent) => {
      if (e.origin !== window.location.origin) return
      const data = e.data as { type?: string; error?: string }
      if (data?.type === "oauth-success") {
        toast.success("Đăng nhập thành công!")
        window.location.href = "/dashboard"
      } else if (data?.type === "oauth-error") {
        toast.error(OAUTH_ERROR_MESSAGES[data.error || ""] || "Đăng nhập thất bại, vui lòng thử lại")
      }
    }
    window.addEventListener("message", handler)
    return () => window.removeEventListener("message", handler)
  }, [])

  return (
    <div className="space-y-3">
      <div className="relative">
        <div className="absolute inset-0 flex items-center">
          <span className="w-full border-t border-border" />
        </div>
        <div className="relative flex justify-center text-xs">
          <span className="bg-background px-2 text-muted-foreground">{label}</span>
        </div>
      </div>
      <div className="flex justify-center gap-3">
        {PROVIDERS.map(({ id, title, icon }) => (
          <button
            key={id}
            type="button"
            title={title}
            aria-label={`Đăng nhập với ${title}`}
            onClick={() => openPopup(id)}
            className="inline-flex size-11 items-center justify-center rounded-xl border border-border bg-card shadow-sm transition-all duration-200 hover:scale-105 hover:bg-accent"
          >
            {icon}
          </button>
        ))}
      </div>
    </div>
  )
}
