"use client"

import * as React from "react"
import { useMutation } from "@tanstack/react-query"
import { useTRPC } from "@/trpc/client"
import { Button } from "@/components/ui/button"
import { Textarea } from "@/components/ui/textarea"
import { Label } from "@/components/ui/label"
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from "@/components/ui/dialog"
import { toast } from "@/components/ui/toast"
import { IconLoader, IconSparkles } from "@/components/icons"

export type AiTemplateKind =
  | "mail_subject"
  | "mail_html"
  | "telegram_text"
  | "notification_title"
  | "notification_html"
  | "rich_description"

interface RelatedField {
  label: string
  value: string
}

interface GenerateAiButtonProps {
  /** Loại nội dung cần sinh */
  kind: AiTemplateKind
  /** Callback khi AI sinh thành công */
  onApply: (output: string) => void
  /** Optional context truyền cho AI (vd subject khi sinh body) */
  related?: RelatedField[]
  /** Label nút (optional) */
  label?: string
  /** Compact size */
  size?: "sm" | "default"
  /** Disabled (vd readOnly) */
  disabled?: boolean
  /** Placeholder cho ô gợi ý */
  hintPlaceholder?: string
}

const DEFAULT_HINTS: Record<AiTemplateKind, string> = {
  mail_subject:
    "VD: Khuyến mãi tháng 12 — giảm 30% tất cả gói website",
  mail_html:
    "VD: Email mời user đăng ký gói website mới ra mắt, có CTA về trang /create-website, mention ưu đãi tháng đầu",
  telegram_text:
    "VD: Thông báo bảo trì hệ thống tối nay 23:00-01:00, kèm link /system-status",
  notification_title:
    "VD: Tài khoản vừa được nạp 500.000đ thành công",
  notification_html:
    "VD: Thông báo user gói website hết hạn trong 3 ngày, kèm link gia hạn",
  rich_description:
    "VD: Mô tả mã nguồn PHP shop bán hàng với giỏ, thanh toán VNPay, quản lý đơn—nêu tính năng, yêu cầu PHP 8+, MySQL",
}

const TITLE_BY_KIND: Record<AiTemplateKind, string> = {
  mail_subject: "Sinh tiêu đề email",
  mail_html: "Sinh nội dung email",
  telegram_text: "Sinh tin nhắn Telegram",
  notification_title: "Sinh tiêu đề thông báo",
  notification_html: "Sinh nội dung thông báo",
  rich_description: "Sinh mô tả chi tiết",
}

/**
 * Nút "Generated by AI" — mở modal cho admin nhập gợi ý, gọi AI sinh nội dung,
 * preview, áp dụng vào field gốc.
 *
 * Yêu cầu: admin đã cấu hình AI ở Settings → AI và bật `enabled`.
 */
export function GenerateAiButton({
  kind,
  onApply,
  related = [],
  label,
  size = "sm",
  disabled = false,
  hintPlaceholder,
}: GenerateAiButtonProps) {
  const trpc = useTRPC()
  const [open, setOpen] = React.useState(false)
  const [hint, setHint] = React.useState("")
  const [output, setOutput] = React.useState<string | null>(null)

  const generateMut = useMutation({
    ...trpc.adminAi.generateTemplate.mutationOptions(),
    onSuccess: (data: any) => {
      setOutput(data.output)
    },
    onError: (err: any) => {
      toast.error(err?.message || "AI sinh nội dung thất bại")
    },
  })

  function handleGenerate() {
    if (!hint.trim()) {
      toast.error("Vui lòng nhập gợi ý")
      return
    }
    generateMut.mutate({ kind, hint: hint.trim(), related })
  }

  function handleApply() {
    if (!output) return
    onApply(output)
    setOpen(false)
    // Reset cho lần sau
    setOutput(null)
    setHint("")
    toast.success("Đã áp dụng nội dung AI")
  }

  function handleOpenChange(o: boolean) {
    setOpen(o)
    if (!o) {
      setOutput(null)
      setHint("")
    }
  }

  const isHtml =
    kind === "mail_html" ||
    kind === "notification_html" ||
    kind === "rich_description"

  return (
    <>
      <Button
        type="button"
        variant="outline"
        size={size}
        disabled={disabled}
        onClick={() => setOpen(true)}
        className="gap-1.5 border-violet-500/40 bg-violet-500/5 text-violet-700 hover:bg-violet-500/10 hover:text-violet-800 dark:text-violet-300"
      >
        <IconSparkles size={size === "sm" ? 13 : 15} />
        {label || "Generated by AI"}
      </Button>

      <Dialog open={open} onOpenChange={handleOpenChange}>
        <DialogContent className="sm:max-w-[720px] max-h-[90vh] overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2">
              <IconSparkles size={18} className="text-violet-600" />
              {TITLE_BY_KIND[kind]}
            </DialogTitle>
            <DialogDescription>
              Mô tả ngắn gọn nội dung muốn sinh. AI sẽ tự định dạng theo
              chuẩn thiết kế chuyên nghiệp.
            </DialogDescription>
          </DialogHeader>

          <div className="space-y-4">
            <div className="space-y-1.5">
              <Label>Gợi ý cho AI</Label>
              <Textarea
                value={hint}
                onChange={(e) => setHint(e.target.value)}
                placeholder={hintPlaceholder || DEFAULT_HINTS[kind]}
                rows={4}
                maxLength={1000}
                disabled={generateMut.isPending}
                className="resize-none"
              />
              <p className="text-[11px] text-muted-foreground text-right">
                {hint.length}/1000
              </p>
            </div>

            {related.length > 0 && (
              <div className="rounded-lg border bg-muted/40 p-3 space-y-1.5">
                <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">
                  Ngữ cảnh AI sẽ tham khảo
                </p>
                {related.map((r, i) => (
                  <div key={i} className="flex gap-2 text-xs">
                    <span className="font-medium text-muted-foreground shrink-0 w-20">
                      {r.label}:
                    </span>
                    <span className="line-clamp-2 text-foreground/80">
                      {r.value || <em className="text-muted-foreground">(trống)</em>}
                    </span>
                  </div>
                ))}
              </div>
            )}

            <div className="flex justify-end gap-2">
              <Button
                type="button"
                variant="outline"
                onClick={() => handleOpenChange(false)}
                disabled={generateMut.isPending}
              >
                Huỷ
              </Button>
              <Button
                type="button"
                onClick={handleGenerate}
                disabled={generateMut.isPending || !hint.trim()}
                className="gap-1.5"
              >
                {generateMut.isPending ? (
                  <IconLoader size={13} className="animate-spin" />
                ) : (
                  <IconSparkles size={13} />
                )}
                {output ? "Sinh lại" : "Sinh nội dung"}
              </Button>
            </div>

            {output && (
              <div className="space-y-2 pt-2 border-t">
                <Label className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">
                  Kết quả AI
                </Label>
                {isHtml ? (
                  <div className="rounded-lg border bg-card overflow-hidden">
                    <div className="border-b border-border bg-muted/40 px-3 py-1.5 flex items-center gap-2">
                      <span className="size-2.5 rounded-full bg-rose-500/70" />
                      <span className="size-2.5 rounded-full bg-amber-500/70" />
                      <span className="size-2.5 rounded-full bg-emerald-500/70" />
                      <span className="ml-2 text-[10px] uppercase tracking-wider text-muted-foreground">
                        Preview
                      </span>
                    </div>
                    <iframe
                      srcDoc={output}
                      className="w-full h-[420px] bg-white"
                      sandbox="allow-same-origin"
                      title="Email preview"
                    />
                  </div>
                ) : (
                  <div className="rounded-lg border bg-card p-3 text-sm whitespace-pre-wrap text-foreground/90 max-h-[280px] overflow-y-auto">
                    {output}
                  </div>
                )}
                <details className="text-xs text-muted-foreground">
                  <summary className="cursor-pointer hover:text-foreground">
                    Xem nguồn ({output.length} ký tự)
                  </summary>
                  <pre className="mt-2 max-h-[240px] overflow-auto rounded-md bg-muted/40 p-2 text-[11px] font-mono whitespace-pre-wrap break-words">
                    {output}
                  </pre>
                </details>
                <div className="flex justify-end gap-2 pt-2">
                  <Button
                    type="button"
                    variant="outline"
                    onClick={() => setOutput(null)}
                  >
                    Bỏ
                  </Button>
                  <Button type="button" onClick={handleApply}>
                    Áp dụng vào form
                  </Button>
                </div>
              </div>
            )}
          </div>
        </DialogContent>
      </Dialog>
    </>
  )
}
